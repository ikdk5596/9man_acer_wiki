export function catalogFor(kind) {
  if (kind === 'soldiers') return SOLDIERS
  if (kind === 'heroes') return HEROES
  if (kind === 'policies') return POLICIES
  throw new Error('올바르지 않은 등급표 종류입니다.')
}
